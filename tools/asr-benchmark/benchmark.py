#!/usr/bin/env python3
"""
Offline WER/CER benchmark: runs a WAXAL language's prepared manifest through
Vosk and/or Whisper (the same engines/registries production uses) and
compares predictions against the manifest's reference transcripts. This
tool is entirely offline and never enters the live contributor scoring
path -- it has no Redis Streams consumer, no Postgres writes, and no
runtime dependency from services/api or the ASR workers on it.

Usage:
    python tools/asr-benchmark/benchmark.py --dataset waxal --language sna --engine whisper
"""

import argparse
import json
import os
import sys
import tempfile
import time

from engines import ENGINES, UnsupportedLanguageError, transcode_to_wav
from metrics import character_error_rate, word_error_rate

REPO_ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
DATA_ROOT = os.path.join(REPO_ROOT, "datasets", "waxal", "data")
REPORTS_ROOT = os.path.join(REPO_ROOT, "reports", "waxal")


def load_manifest(language: str) -> list[dict]:
    manifest_path = os.path.join(DATA_ROOT, language, "manifest.jsonl")
    if not os.path.exists(manifest_path):
        raise SystemExit(f"No manifest at {manifest_path} -- run prepare.py --language {language} first")
    records = []
    with open(manifest_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def run_engine(engine_name: str, language: str, records: list[dict]) -> dict:
    engine = ENGINES[engine_name]()

    if not engine.supports(language):
        return {"engine": engine_name, "supported": False}

    wer_scores = []
    cer_scores = []
    durations_ms = []
    success_count = 0
    failure_count = 0

    with tempfile.TemporaryDirectory() as tmp_dir:
        for record in records:
            audio_path = os.path.join(REPO_ROOT, record["audioPath"])
            wav_path = os.path.join(tmp_dir, os.path.basename(audio_path) + ".norm.wav")
            try:
                transcode_to_wav(audio_path, wav_path)
                start = time.monotonic()
                hypothesis = engine.transcribe(wav_path, language)
                elapsed_ms = (time.monotonic() - start) * 1000
            except Exception as exc:  # noqa: BLE001 -- benchmark keeps going on a per-sample failure
                print(f"  [{engine_name}] failed on {record['audioPath']}: {exc}")
                failure_count += 1
                continue

            reference = record.get("transcript", "")
            wer_scores.append(word_error_rate(reference, hypothesis))
            cer_scores.append(character_error_rate(reference, hypothesis))
            durations_ms.append(elapsed_ms)
            success_count += 1

    return {
        "engine": engine_name,
        "supported": True,
        "sampleCount": len(records),
        "successCount": success_count,
        "failureCount": failure_count,
        "wer": round(sum(wer_scores) / len(wer_scores), 4) if wer_scores else None,
        "cer": round(sum(cer_scores) / len(cer_scores), 4) if cer_scores else None,
        "avgProcessingTimeMs": round(sum(durations_ms) / len(durations_ms), 1) if durations_ms else None,
    }


def write_report(language: str, language_name: str, results: list[dict]) -> str:
    os.makedirs(REPORTS_ROOT, exist_ok=True)
    report = {
        "dataset": "waxal",
        "languageTag": language,
        "language": language_name,
        "results": results,
    }
    report_path = os.path.join(REPORTS_ROOT, f"{language_name.lower()}.json")
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    return report_path


def regenerate_summary() -> str:
    os.makedirs(REPORTS_ROOT, exist_ok=True)
    lines = ["# WAXAL benchmark summary", "", "Generated by tools/asr-benchmark/benchmark.py -- do not hand-edit.", ""]
    for filename in sorted(os.listdir(REPORTS_ROOT)):
        if not filename.endswith(".json"):
            continue
        with open(os.path.join(REPORTS_ROOT, filename), "r", encoding="utf-8") as f:
            report = json.load(f)
        lines.append(f"## {report['language']} ({report['languageTag']})")
        lines.append("")
        best_engine = None
        best_wer = None
        for result in report["results"]:
            if not result.get("supported"):
                lines.append(f"- **{result['engine']}**: unsupported")
                continue
            wer = result.get("wer")
            lines.append(
                f"- **{result['engine']}**: WER {wer if wer is not None else 'n/a'}, "
                f"CER {result.get('cer', 'n/a')}, "
                f"{result.get('successCount', 0)}/{result.get('sampleCount', 0)} samples, "
                f"avg {result.get('avgProcessingTimeMs', 'n/a')} ms"
            )
            if wer is not None and (best_wer is None or wer < best_wer):
                best_wer = wer
                best_engine = result["engine"]
        if best_engine:
            lines.append("")
            lines.append(f"Best engine: **{best_engine}** (WER {best_wer})")
        lines.append("")

    summary_path = os.path.join(REPORTS_ROOT, "summary.md")
    with open(summary_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return summary_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Offline WER/CER benchmark against WAXAL data")
    parser.add_argument("--dataset", required=True, choices=["waxal"])
    parser.add_argument("--language", required=True, help="WAXAL ASR language tag, e.g. sna")
    parser.add_argument("--engine", required=True, choices=["vosk", "whisper", "both"])
    args = parser.parse_args()

    records = load_manifest(args.language)
    language_name = records[0]["language"] if records else args.language
    print(f"Loaded {len(records)} record(s) for {language_name} ({args.language})")

    engine_names = ["vosk", "whisper"] if args.engine == "both" else [args.engine]
    results = []
    for engine_name in engine_names:
        print(f"Running {engine_name} ...")
        try:
            result = run_engine(engine_name, args.language, records)
        except UnsupportedLanguageError:
            result = {"engine": engine_name, "supported": False}
        results.append(result)
        if result.get("supported"):
            print(f"  WER={result['wer']} CER={result['cer']} success={result['successCount']}/{result['sampleCount']}")
        else:
            print(f"  {engine_name}: unsupported for language={args.language}")

    report_path = write_report(args.language, language_name, results)
    summary_path = regenerate_summary()
    print(f"Wrote {report_path}")
    print(f"Wrote {summary_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
